/**
 * The token reference at the end of DESIGN.md, rewritten on every build.
 *
 * Everything above the marker is written by hand; everything below it comes
 * from the Figma export and tokens.css, so it can't drift from them. It's a
 * guide to choosing a token, not a copy of tokens.css: colours are listed by
 * name and use only, so nobody copies a hex value; scales keep their values,
 * because there the number is how you choose. Uses are the Figma descriptions.
 */
import { readFile, writeFile } from 'node:fs/promises'

export const MARKER = '<!-- Generated by npm run build from the Figma export and tokens.css. Edit above this line. -->'

/** Headings for the first segment of a name; anything new falls back to the segment itself. */
const GROUPS = {
  bg: 'Backgrounds',
  border: 'Lines',
  fill: 'Fills and overlays',
  text: 'Text',
  accent: 'Accent',
  status: 'Status',
  series: 'Chart series',
  focus: 'Focus',
  window: 'Window',
  spacing: 'Spacing',
  radius: 'Radius',
  'font-size': 'Font sizes',
  'font-family': 'Font families',
  opacity: 'Opacity',
  shadow: 'Shadows',
  titlebar: 'Layout',
  rail: 'Layout',
  section: 'Cards',
  row: 'Cards',
  ease: 'Motion',
  duration: 'Motion',
  weight: 'Font weights',
}

const cssName = (figmaName) => `--${figmaName.replace(/\//g, '-')}`
const code = (text) => `\`${text}\``
const heading = (prefix) => GROUPS[prefix] ?? prefix[0].toUpperCase() + prefix.slice(1)
const lowerFirst = (text) => text[0].toLowerCase() + text.slice(1)

/** `--name: value;` declarations of one rule in tokens.css, trailing comments dropped. */
function declarations(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start === -1) return new Map()
  const body = css.slice(start, css.indexOf('\n}', start))
  return new Map([...body.matchAll(/^\s*(--[\w-]+):\s*(.+?);(?:\s*\/\*.*\*\/)?$/gm)].map(([, name, value]) => [name, value]))
}

function groupBy(items, key) {
  const groups = new Map()
  for (const item of items) {
    const k = key(item)
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(item)
  }
  return groups
}

export async function writeDesign({ path, variables, textStyles, code: codeTokens, css }) {
  const dark = declarations(css, ':root')
  const light = declarations(css, ':root.theme-light')
  // A font stack reads as its first font.
  const short = (value) => value.split(',')[0].replace(/^'|'$/g, '')

  const cssVars = variables.filter((v) => v.code)
  const colours = cssVars.filter((v) => v.type === 'COLOR')
  const others = cssVars.filter((v) => v.type !== 'COLOR')
  const out = []

  // Plain numbers read as text; expressions stay as code.
  const show = (value) => (value.includes('(') ? code(value) : value)
  const note = (v) => (v.description ? ` (${lowerFirst(v.description)})` : '')

  out.push('## Token reference', '', 'Names and uses, from Figma. The values are in `tokens.css`; Dark and Light differ only in colour and shadow.', '', '### Colour', '')
  for (const [prefix, vars] of groupBy(colours, (v) => v.name.split('/')[0])) {
    out.push(`- **${heading(prefix)}:** ${vars.map((v) => `${code(cssName(v.name))}${note(v)}`).join(', ')}`)
  }

  out.push('', '### Scales', '')
  for (const [prefix, vars] of groupBy(others, (v) => v.name.split('/')[0])) {
    const value = (v) => dark.get(cssName(v.name))
    const px = (v) => value(v)?.match(/^([\d.]+)px$/)?.[1]
    // Pixel scales read smallest to largest; Figma lists late additions last.
    if (vars.every(px)) vars.sort((a, b) => px(a) - px(b))
    // spacing/12 is 12px, so the name already says the value.
    const numbered = vars.every((v) => px(v) === v.name.split('/')[1])
    const list = numbered
      ? `${code(`--${prefix}-<n>`)}, n in px: ${vars.map((v) => `${px(v)}${note(v)}`).join(', ')}`
      : vars.map((v) => `${code(cssName(v.name))} ${show(short(value(v)))}${note(v)}`).join(', ')
    out.push(`- **${heading(prefix)}:** ${list}`)
  }

  out.push('', '### Text styles', '', 'Each style is four variables, `--type-<style>-size`, `-weight`, `-line-height` and `-letter-spacing`; use all four.', '')
  out.push('| Style | Variables | Size, weight | Use |', '| --- | --- | --- | --- |')
  for (const s of textStyles) {
    const slug = s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
    const numeric = s.boundVariables?.fontFamily === 'font-family/numeric' ? ', Questrial' : ''
    out.push(`| ${s.name} | ${code(`--type-${slug}-*`)} | ${s.fontSize}px ${dark.get(`--type-${slug}-weight`)}${numeric} | ${s.description.replace(/\|/g, '\\|')} |`)
  }

  const codeNames = Object.keys(codeTokens.tokens)
  out.push('', '### Code-only tokens', '', 'What Figma variables can\'t hold, from `src/code-tokens.json`.', '')
  for (const [group, names] of groupBy(codeNames, (n) => heading(n.slice(2).split('-')[0]))) {
    // Long or per-theme values (shadows, calc()) are named only; tokens.css has them.
    const shown = (n) => dark.get(n).length <= 24 && (light.get(n) ?? dark.get(n)) === dark.get(n)
    out.push(`- **${group}:** ${names.map((n) => (shown(n) ? `${code(n)} ${show(dark.get(n))}` : code(n))).join(', ')}`)
  }

  const current = await readFile(path, 'utf8')
  const at = current.indexOf(MARKER)
  if (at === -1) throw new Error(`DESIGN.md has lost its marker line; put it back: ${MARKER}`)
  await writeFile(path, `${current.slice(0, at + MARKER.length)}\n\n${out.join('\n')}\n`)
  return { colours: colours.length, others: others.length, styles: textStyles.length, code: codeNames.length }
}
