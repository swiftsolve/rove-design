/**
 * The token reference at the end of DESIGN.md, rewritten on every build.
 *
 * Everything above the marker is written by hand; everything below it comes
 * from the Figma export and tokens.css, so it can't drift from them. Values are
 * what tokens.css sets (Dark on :root, Light on :root.theme-light); colours also
 * name the Palette shade or token they point at, and uses are the Figma
 * descriptions.
 */
import { readFile, writeFile } from 'node:fs/promises'

export const MARKER = '<!-- Generated by npm run build from the Figma export and tokens.css. Edit above this line. -->'

/** Headings for the first segment of a Figma name; anything new falls back to the segment itself. */
const GROUPS = {
  bg: 'Backgrounds',
  border: 'Lines',
  fill: 'Fills and overlays',
  text: 'Text',
  accent: 'Accent',
  status: 'Status',
  series: 'Chart series',
  focus: 'Focus',
  window: 'Window',
  spacing: 'Spacing',
  radius: 'Radius',
  'font-size': 'Font sizes',
  'font-family': 'Font families',
  opacity: 'Opacity',
}

const cssName = (figmaName) => `--${figmaName.replace(/\//g, '-')}`
const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const code = (text) => `\`${text}\``
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n')

/** `--name: value;` declarations of one rule in tokens.css, trailing comments dropped. */
function declarations(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start === -1) return new Map()
  const body = css.slice(start, css.indexOf('\n}', start))
  return new Map([...body.matchAll(/^\s*(--[\w-]+):\s*(.+?);(?:\s*\/\*.*\*\/)?$/gm)].map(([, name, value]) => [name, value]))
}

function groupBy(items, key) {
  const groups = new Map()
  for (const item of items) {
    const k = key(item)
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(item)
  }
  return groups
}

const heading = (prefix) => GROUPS[prefix] ?? prefix[0].toUpperCase() + prefix.slice(1)

export async function writeDesign({ path, variables, textStyles, code: codeTokens, css, rawValue }) {
  const dark = declarations(css, ':root')
  const light = declarations(css, ':root.theme-light')
  const valueIn = (name, mode) => (mode === 'Light' && light.get(name)) || dark.get(name)

  const colour = (v, mode) => {
    const alias = v.values[mode]?.alias
    return `${code(rawValue(v, mode))}${alias ? ` ${alias}` : ''}`
  }

  const cssVars = variables.filter((v) => v.code)
  const colours = cssVars.filter((v) => v.type === 'COLOR')
  const others = cssVars.filter((v) => v.type !== 'COLOR')
  const out = []

  out.push('## Colour', '', 'Dark and Light values, with the Palette shade or token each one points at.')
  for (const [prefix, vars] of groupBy(colours, (v) => v.name.split('/')[0])) {
    out.push('', `### ${heading(prefix)}`, '', table(['Token', 'Dark', 'Light', 'Use'], vars.map((v) => [code(cssName(v.name)), colour(v, 'Dark'), colour(v, 'Light'), v.description])))
  }

  out.push('', '## Spacing, type and opacity')
  for (const [prefix, vars] of groupBy(others, (v) => v.name.split('/')[0])) {
    const px = (v) => dark.get(cssName(v.name))?.match(/^([\d.]+)px$/)?.[1]
    // Pixel scales read smallest to largest; Figma lists late additions last.
    if (vars.every(px)) vars.sort((a, b) => px(a) - px(b))
    out.push('', `### ${heading(prefix)}`, '', table(['Token', 'Value', 'Use'], vars.map((v) => [code(cssName(v.name)), code(dark.get(cssName(v.name))), v.description])))
  }

  out.push('', '## Text styles', '', 'Each style is four variables: `--type-<style>-size`, `-weight`, `-line-height` and `-letter-spacing`. Use all four together.', '')
  out.push(table(['Style', 'Variables', 'Size', 'Weight', 'Line height', 'Letter spacing', 'Use'], textStyles.map((s) => {
    const slug = s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
    const get = (part) => dark.get(`--type-${slug}-${part}`)
    const sizeVar = s.boundVariables?.fontSize
    const font = s.boundVariables?.fontFamily ? `, ${s.boundVariables.fontFamily.split('/')[1]}` : ''
    return [s.name, code(`--type-${slug}-*`), `${s.fontSize}px${sizeVar ? ` (${code(cssName(sizeVar))})` : ''}${font}`, get('weight'), get('line-height'), get('letter-spacing'), s.description]
  })))

  const codeNames = Object.keys(codeTokens.tokens)
  out.push('', '## Code-only tokens', '', 'What Figma variables can\'t hold: shadows, layout, motion and weights, from `src/code-tokens.json`.', '')
  out.push(table(['Token', 'Dark', 'Light'], codeNames.map((name) => {
    const d = valueIn(name, 'Dark')
    const l = valueIn(name, 'Light')
    return [code(name), code(d), l === d ? 'Same' : code(l)]
  })))

  const current = await readFile(path, 'utf8')
  const at = current.indexOf(MARKER)
  if (at === -1) throw new Error(`DESIGN.md has lost its marker line; put it back: ${MARKER}`)
  await writeFile(path, `${current.slice(0, at + MARKER.length)}\n\n${out.join('\n')}\n`)
  return { colours: colours.length, others: others.length, styles: textStyles.length, code: codeNames.length }
}
